-- Sri Bitara 2026 — pangkalan data Supabase (ganti Google Sheet + Drive).
-- Semua jadual dikunci (RLS tanpa polisi): hanya Edge Function "api" (service role) boleh baca/tulis.
-- ord = susunan baris, sama seperti susunan baris dalam Google Sheet.

create table public.anugerah  (ord bigint generated by default as identity, id text primary key, kat text not null default '', nama text not null default '', sasaran text not null default '');
create table public.penerima  (ord bigint generated by default as identity, id text primary key, aid text not null default '', tahun text not null default '', kelas text not null default '', nama text not null default '', catatan text not null default '', status text not null default '', hadir text not null default '');  -- hadir = masa murid ditanda hadir (Kehadiran)
create table public.ajk       (ord bigint generated by default as identity, id text primary key, jk text not null default '', ahli text not null default '', tugas text not null default '');
create table public.tentatif  (ord bigint generated by default as identity, id text primary key, masa text not null default '', acara text not null default '', pic text not null default '');
create table public.persiapan (ord bigint generated by default as identity, id text primary key, nama text not null default '', peratus text not null default '');
create table public.galeri    (ord bigint generated by default as identity, id text primary key, fid text not null default '', kat text not null default '', kapsyen text not null default '', masa text not null default '');
-- foto AJK: n = nama guru (cth. "Harsidi Bin Junick"), fid = laluan fail dalam bucket "foto"
create table public.foto_ajk  (n text primary key, fid text not null);
create table public.tetapan   (kunci text primary key, nilai jsonb);
-- PIN admin. Tukar di Table Editor → admin → pin. pin_gas = ADMIN_PIN dalam Code.gs (untuk senarai murid Hadir).
create table public.admin     (id int primary key check (id = 1), pin text not null, gagal int not null default 0, sejak timestamptz, pin_gas text);
-- salinan senarai murid Hadir@SKBT (dari Code.gs), dikemas kini di latar belakang
create table public.murid_cache (id int primary key check (id = 1), roster jsonb not null, masa timestamptz not null default now());

create index on public.penerima (aid);

do $$ declare t text; begin
  foreach t in array array['anugerah','penerima','ajk','tentatif','persiapan','galeri','foto_ajk','tetapan','admin','murid_cache'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

-- ganti seluruh jadual dalam satu transaksi (seperti writeTable_ dalam Code.gs), ikut susunan tatasusunan
create function public.ganti_jadual(t text, r jsonb) returns void language plpgsql security definer set search_path = '' as $$
declare cols text;
begin
  if t not in ('anugerah','penerima','ajk','tentatif','persiapan','galeri') then raise exception 'Jadual tidak sah'; end if;
  select string_agg(quote_ident(column_name), ',' order by ordinal_position) into cols
    from information_schema.columns where table_schema = 'public' and table_name = t and column_name <> 'ord';
  execute format('delete from public.%I where true', t);
  execute format('insert into public.%1$I (%2$s) select %2$s from jsonb_populate_recordset(null::public.%1$I, $1) with ordinality order by ordinality', t, cols) using r;
end $$;

-- 'ok' | 'salah' | 'kunci' — 10 cubaan salah mengunci 10 minit (seperti checkPin_ dalam Code.gs)
create function public.semak_pin(p text) returns text language plpgsql security definer set search_path = '' as $$
declare a public.admin;
begin
  select * into a from public.admin where id = 1 for update;
  if not found then return 'tiada'; end if;
  if a.sejak < now() - interval '10 minutes' then a.gagal := 0; end if;
  if a.gagal >= 10 then return 'kunci'; end if;
  if p = a.pin then return 'ok'; end if;
  update public.admin set gagal = a.gagal + 1, sejak = now() where id = 1;
  return 'salah';
end $$;

-- semua data dalam satu panggilan (tiada had 1000 baris seperti select biasa)
create function public.semua_data() returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'anugerah',  coalesce((select jsonb_agg(to_jsonb(x) - 'ord' order by x.ord) from public.anugerah x), '[]'),
    'penerima',  coalesce((select jsonb_agg(to_jsonb(x) - 'ord' order by x.ord) from public.penerima x), '[]'),
    'ajk',       coalesce((select jsonb_agg(to_jsonb(x) - 'ord' order by x.ord) from public.ajk x), '[]'),
    'tentatif',  coalesce((select jsonb_agg(to_jsonb(x) - 'ord' order by x.ord) from public.tentatif x), '[]'),
    'persiapan', coalesce((select jsonb_agg(to_jsonb(x) - 'ord' order by x.ord) from public.persiapan x), '[]'),
    'galeri',    coalesce((select jsonb_agg(to_jsonb(x) - 'ord' order by x.ord) from public.galeri x), '[]'),
    'fotoAjk',   coalesce((select jsonb_agg(to_jsonb(x) order by x.n) from public.foto_ajk x), '[]'),
    'tetapan',   coalesce((select jsonb_object_agg(kunci, nilai) from public.tetapan), '{}'))
$$;

revoke execute on function public.ganti_jadual(text, jsonb), public.semak_pin(text), public.semua_data() from public, anon, authenticated;

